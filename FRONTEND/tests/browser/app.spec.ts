import { test, expect } from '@playwright/test'
const text = 'Alex Morgan scored 85 on March 12, 2026.'
const refined = 'On March 12, 2026, Alex Morgan scored 85.'
test('landing navigation and mobile layout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Make every word feel human/ })).toBeVisible()
  await expect(page.locator('.hero-content')).toHaveCSS('opacity', '1')
  await page.screenshot({ path: '/tmp/verba-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Explore the possibilities' }).click()
  await expect(page.getByRole('heading', { name: 'Better expression. The same meaning.' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open menu' }).click()
  await page.locator('.nav-links').getByRole('button', { name: 'Workspace' }).click()
  await expect(page.getByRole('heading', { name: 'Humanization Studio.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto('/')
  await expect(page.locator('.hero-content')).toHaveCSS('opacity', '1')
  await page.screenshot({ path: '/tmp/verba-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
test('empty input and service failure keep original text', async ({ page }) => {
  await page.goto('/#workspace')
  await page.getByRole('button', { name: 'Analyze & refine' }).click()
  await expect(page.getByRole('alert')).toContainText('Paste or type')
  await page.getByRole('button', { name: 'Load example' }).click()
  const value = await page.getByRole('textbox', { name: 'Original text' }).inputValue()
  await page.route('**/api/refine', route => route.fulfill({ status: 503, json: { error: 'The AI service is not configured yet.' } }))
  await page.getByRole('button', { name: 'Analyze & refine' }).click()
  await expect(page.getByRole('alert')).toContainText('not configured')
  await expect(page.getByRole('textbox', { name: 'Original text' })).toHaveValue(value)
  await expect(page.getByRole('heading', { name: 'Room for your best words.' })).toBeVisible()
})
test('mocked result, reports, download, history, preferences', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.route('**/api/refine', route => route.fulfill({ json: {
    id: 'test-session', timestamp: new Date().toISOString(), original: text, revised: refined,
    options: { context: 'General Communication', tone: 'Professional', intensity: 'Balanced' },
    findings: [], changes: [{ original: text, revised: refined, reason: 'Moved the date for a clearer opening.' }],
    verification: { status: 'Checks passed', preserved: ['Alex Morgan', '85', 'March 12, 2026'], missing: [], added: [], warnings: [], claims: [] },
  } }))
  await page.goto('/#workspace')
  await page.getByRole('textbox', { name: 'Original text' }).fill(text)
  await page.getByRole('button', { name: 'Analyze & refine' }).click()
  await expect(page.locator('.output-text')).toHaveText(refined)
  await page.getByRole('button', { name: 'Copy refined text' }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(refined)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download refined text' }).click()
  expect((await download).suggestedFilename()).toBe('humanize-ai-refined.txt')
  await page.getByRole('button', { name: 'Comparison', exact: true }).click()
  await expect(page.locator('.added-word').first()).toBeVisible()
  await page.getByRole('button', { name: 'Verification report', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Checks passed', exact: true })).toBeVisible()
  await page.locator('.nav-links').getByRole('button', { name: 'History' }).click()
  await expect(page.locator('.history-card')).toHaveCount(1)
  await page.reload()
  await page.getByRole('button', { name: 'Reopen' }).click()
  await expect(page.locator('.output-text')).toHaveText(refined)
  await page.locator('.nav-links').getByRole('button', { name: 'Settings' }).click()
  await page.getByLabel('DEFAULT TONE').selectOption('Conversational')
  await page.getByRole('button', { name: 'Save preferences' }).click()
  await page.reload()
  await expect(page.getByLabel('DEFAULT TONE')).toHaveValue('Conversational')
  await page.locator('.nav-links').getByRole('button', { name: 'History' }).click()
  await page.getByRole('button', { name: 'Clear history', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Keep my history' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByRole('button', { name: 'Delete session' }).click()
  await expect(page.locator('.history-card')).toHaveCount(0)
})
